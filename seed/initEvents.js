async function seed() {
  const uri = process.env.MONGODB_URI;
  if (!uri) {
    console.error("MONGODB_URI not set");
    process.exit(1);
  }

  await mongoose.connect(uri);
  console.log("Connected to MongoDB");

  for (const item of initialEvents) {
    const existing = await Event.findOne({ $or: [{ id: item.id }, { slug: item.slug }] });
    if (!existing) {
      await Event.create(item);
      console.log(`Created event: ${item.title}`);
    } else {
      await Event.updateOne({ _id: existing._id }, { $set: item });
      console.log(`Updated event: ${item.title}`);
    }
  }

  const count = await Event.countDocuments();
  console.log(`Total events in database: ${count}`);
  await mongoose.disconnect();
  console.log("Disconnected");
}

seed().catch((err) => {
  console.error("Seed error:", err);
  process.exit(1);
});
